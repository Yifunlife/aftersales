import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import fs from 'node:fs';
import vm from 'node:vm';
import {engineeringPeople,validateEngineeringAssignment} from '../lib/engineering-people.mjs';
const sql=new DatabaseSync(':memory:');sql.exec('CREATE TABLE employees(id TEXT,name TEXT,role TEXT,active INTEGER)');
for(const r of [['1','真实工程','工程人员',1],['2','停用工程','工程人员',0],['3','采购','采购人员',1],['4','重名','工程人员',1],['5','重名','工程人员',1]])sql.prepare('INSERT INTO employees VALUES(?,?,?,?)').run(...r);
const db={prepare(query){return {async all(){return {results:sql.prepare(query).all()}}}}};
assert.deepEqual(await engineeringPeople(db),['真实工程']);
const old={stage:'工程下单'},assignment={orderGroup:'工程部',orderAssignee:'真实工程'};
await validateEngineeringAssignment(db,old,assignment);
for(const name of ['停用工程','采购','周工程','重名'])await assert.rejects(()=>validateEngineeringAssignment(db,old,{...assignment,orderAssignee:name}),/已启用/);
await assert.rejects(()=>validateEngineeringAssignment(db,old,{engineering:{confirmed:true,engineer:'周工程',orderGroup:'工程一组'}}),/已启用/);
await validateEngineeringAssignment(db,{stage:'采购',engineering:{engineer:'旧记录'}},{stage:'采购',engineering:{engineer:'旧记录'}});
const source=fs.readFileSync(new URL('../app-fragment.html',import.meta.url),'utf8');
const helpers=source.slice(source.indexOf('let staffPeople=[];'),source.indexOf('function updateOrderingPeople('));
const context=vm.createContext({esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')});
vm.runInContext(helpers+`;staffPeople=[{name:'工程甲',role:'工程人员'},{name:'仓库乙',role:'仓库人员'},{name:'管理丙',role:'管理员'}];`,context);
const dropdown=vm.runInContext("staffSelect('nextOwner','负责人','仓库乙',['仓库人员'])",context);
assert(dropdown.includes('<select'));assert(dropdown.includes('仓库乙'));assert(dropdown.includes('管理丙'));assert(!dropdown.includes('工程甲'));assert(dropdown.includes('selected'));
assert.equal(vm.runInContext("operationNextRoles({stage:'品质检验'},'return')[0]",context),'生产人员');
assert.equal(vm.runInContext("operationNextRoles({stage:'品质检验'})[0]",context),'仓库人员');
console.log('Engineering directory: active real roles only, stale/demo/ambiguous assignments rejected, history preserved.');
